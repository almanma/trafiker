function a(medioId: string, titular: string, hora: string, tono: Tono, intensidad: 1 | 2 | 3): Articulo {
  const slug = titular
    .toLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .slice(0, 48);
  return { medioId, titular, hora, tono, intensidad, url: urlEjemplo(medioId, slug) };
}

